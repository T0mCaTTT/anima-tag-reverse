/**
 * 建表：
 *   surface → [{ zh, en }]
 * 同时把「汉字骨架」也注册一份（青い髪 → 青髪），因为日文常把假名夹在汉字里。
 */
export function buildJpTable() {
  const map = new Map();
  for (const [jp, zh, en] of [...JP_TERMS, ...JP_VERBS]) {
    for (const variant of String(jp).split(/\s+/).filter(Boolean)) {
      const key = variant.toLowerCase();
      if (!map.has(key)) map.set(key, { zh, en });
      const skeleton = key.replace(/[\u3040-\u309f]/g, '');   // 去平假名
      if (skeleton && skeleton !== key && skeleton.length >= 1 && !map.has(skeleton)) {
        map.set(skeleton, { zh, en });
      }
    }
  }
  return { map, maxLen: Math.max(...[...map.keys()].map(k => k.length)), particles: JP_PARTICLES };
}
