/** 归一化成 `{ 作品key: [别名…] }`（归一化在这里做，加载时直接用） */
export function buildSeriesZhIndex(normalizeName, keyOf) {
  const out = {};
  for (const [tag, aliases] of Object.entries(SERIES_ZH)) {
    const k = keyOf(tag);
    if (!k) continue;
    out[k] = [...new Set((aliases || []).map(a => String(a).trim()).filter(Boolean))];
  }
  return out;
}
